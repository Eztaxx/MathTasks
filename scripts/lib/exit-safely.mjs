/*
 * Остановка скрипта сразу после запросов к базе.
 *
 * process.exit() на Windows роняет Node — «Assertion failed:
 * !(handle->flags & UV_HANDLE_CLOSING), file src\win\async.c», — если застаёт
 * соединения fetch в момент закрытия. Под нагрузкой так было в 4 запусках
 * из 8; с принудительным закрытием соединений прямо перед выходом — в 8 из 8.
 * Короткая пауза даёт им закрыться: 0 из 8.
 *
 * В конце скрипта лучше process.exitCode — процесс выйдет сам. Эта функция —
 * для остановки посреди скрипта (сухой прогон, ошибка доступа), где выход
 * обязан прервать выполнение, чтобы дальше не пошла запись в базу. Поэтому
 * она всё-таки зовёт process.exit() и не возвращается.
 */
export async function exitSafely(code = 0) {
  await new Promise(resolve => setTimeout(resolve, 200));
  process.exit(code);
}
