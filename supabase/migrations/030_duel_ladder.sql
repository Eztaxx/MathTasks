-- Миграция 030: дуэль-лесенка — сложность не выбирается, а растёт по ходу минуты
--
-- Раньше у дуэли выбирались категория и сложность: 7 × 3 = 21 таблица
-- лидеров, почти все пустые. Теперь сложность одна на всех — лесенка:
-- первые примеры базовые, дальше продвинутые, потом экспертные (duel.js:
-- LADDER_TIERS). Таблица лидеров — одна на категорию.
--
-- В базе такие попытки хранятся с diff = 'ladder'. Старые попытки одной
-- сложности остаются как есть: в таблицу лесенки и в соперники-записи они
-- не попадают — у них другое поколение gen (duel.js: runGen) и другая
-- сложность. Удалять их незачем.
--
-- Запускать в Supabase: SQL Editor → New query → Run (после 028).
-- Пока миграция не применена, начало попытки на сервере отклоняется
-- проверкой diff, и дуэль идёт без записи: без таблицы и без соперников-
-- записей, но с живым соперником и с другом по ссылке.

alter table public.duel_runs drop constraint if exists duel_runs_diff_check;
alter table public.duel_runs add constraint duel_runs_diff_check
  check (diff in ('normal', 'hard', 'expert', 'ladder'));
