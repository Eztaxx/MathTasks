-- 024: варианты ответа для автопроверки.
--
-- Ученик по-прежнему видит answer_latex как есть («120 книг»), а при
-- проверке его ответ сверяется ещё и с вариантами из answer_check — по
-- одному на строку («120»). Так проверяются ответы со словами, которые сами
-- по себе автоматически не сверить. Без вариантов у такой задачи вместо
-- поля ответа — самопроверка («Сверить с ответом» → «Сошлось / Не сошлось»).
--
-- answer_check_lv — варианты для латышской версии («jā» вместо «да»);
-- пустой — берутся русские.
--
-- Политики RLS заданы на таблицу целиком и на новые колонки распространяются.

alter table public.tasks add column if not exists answer_check text;
alter table public.tasks add column if not exists answer_check_lv text;
