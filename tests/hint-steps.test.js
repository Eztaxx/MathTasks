import { describe, expect, it } from 'vitest';
import lib from '../public/lib.js';

const { splitHintSteps, hintStepsRevealAnswer } = lib;

/* Подсказка из шагов живёт в том же поле, что и раньше: шаги разделены
   строкой «---». Старая подсказка без разделителя — один шаг. */
describe('шаги подсказки', () => {
  it('подсказка без разделителя — один шаг', () => {
    expect(splitHintSteps('Вынесите общий множитель за скобки.')).toEqual(['Вынесите общий множитель за скобки.']);
  });

  it('пустая подсказка — ни одного шага', () => {
    expect(splitHintSteps('')).toEqual([]);
    expect(splitHintSteps(null)).toEqual([]);
    expect(splitHintSteps('  \n---\n  ')).toEqual([]);
  });

  it('шаги режутся по строке из трёх дефисов', () => {
    expect(splitHintSteps('Начните с формулы.\n---\nПодставьте $a = 3$.\n---\nУпростите.'))
      .toEqual(['Начните с формулы.', 'Подставьте $a = 3$.', 'Упростите.']);
  });

  it('понимает CRLF и пробелы вокруг разделителя', () => {
    expect(splitHintSteps('Шаг один\r\n  ---  \r\nШаг два')).toEqual(['Шаг один', 'Шаг два']);
  });

  it('разделитель в конце не даёт пустого шага', () => {
    expect(splitHintSteps('Шаг один\n---\nШаг два\n---')).toEqual(['Шаг один', 'Шаг два']);
  });

  it('дефисы внутри строки — это текст, а не разделитель', () => {
    expect(splitHintSteps('Сравните $a---b$ и $c$')).toEqual(['Сравните $a---b$ и $c$']);
  });
});

describe('подсказка, выдающая ответ', () => {
  it('одиночная подсказка с ответом — проблема', () => {
    expect(hintStepsRevealAnswer('$x = 4$', 'Получится $x = 4$.')).toEqual([0]);
  });

  it('последний шаг вправе подвести к ответу', () => {
    expect(hintStepsRevealAnswer('$x = 4$', 'Перенесите слагаемые.\n---\nОтсюда $2x = 8$, то есть $x = 4$.')).toEqual([]);
  });

  it('ранний шаг с ответом — проблема, и он назван', () => {
    expect(hintStepsRevealAnswer('$x = 4$', 'Сразу видно, что $x = 4$.\n---\nПроверьте подстановкой.')).toEqual([0]);
  });

  it('подсказка без чисел ответа — всё в порядке', () => {
    expect(hintStepsRevealAnswer('$x = 4$', 'Вынесите $x$ за скобки.\n---\nРазделите обе части.')).toEqual([]);
  });
});
